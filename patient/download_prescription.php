<?php

session_start();

include("../config/database.php");

require('../library/fpdf186/fpdf.php');

if(!isset($_GET['id']))
{
    die("Prescription ID Missing");
}

$prescription_id = $_GET['id'];

$query = mysqli_query(
$conn,
"SELECT p.*,u.full_name,d.doctor_name
FROM prescriptions p
LEFT JOIN users u
ON p.user_id=u.user_id
LEFT JOIN doctors d
ON p.doctor_id=d.doctor_id
WHERE p.prescription_id='$prescription_id'"
);

$data = mysqli_fetch_assoc($query);

$pdf = new FPDF();

$pdf->AddPage();

$pdf->SetFont('Arial','B',18);

$pdf->Cell(
190,
10,
'Smart Healthcare Platform',
0,
1,
'C'
);

$pdf->Ln(5);

$pdf->SetFont('Arial','B',14);

$pdf->Cell(
190,
10,
'Medical Prescription',
0,
1,
'C'
);

$pdf->Ln(10);

$pdf->SetFont('Arial','',12);

$pdf->Cell(
50,
10,
'Patient Name:'
);

$pdf->Cell(
100,
10,
$data['full_name'],
0,
1
);

$pdf->Cell(
50,
10,
'Doctor Name:'
);

$pdf->Cell(
100,
10,
$data['doctor_name'],
0,
1
);

$pdf->Cell(
50,
10,
'Medicine:'
);

$pdf->Cell(
100,
10,
$data['medicine_name'],
0,
1
);

$pdf->Cell(
50,
10,
'Dosage:'
);

$pdf->Cell(
100,
10,
$data['dosage'],
0,
1
);

$pdf->Cell(
50,
10,
'Condition:'
);

$pdf->MultiCell(
130,
10,
$data['patient_condition']
);

$pdf->Cell(
50,
10,
'Remarks:'
);

$pdf->MultiCell(
130,
10,
$data['remarks']
);

$pdf->Ln(10);

$pdf->Cell(
190,
10,
'Generated By Smart Healthcare Platform',
0,
1,
'C'
);

$pdf->Output(
'D',
'Prescription_'.$prescription_id.'.pdf'
);

?>